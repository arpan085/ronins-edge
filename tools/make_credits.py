#!/usr/bin/env python3
"""v13: write game/CREDITS.md from the audio pick list and source metadata.

Inputs (produced while the v0.13 audio was assembled):
  /tmp/audio_credits.json   [[game sound set, source file], ...]
  /tmp/fs/meta.json         Freesound search results (id, user, title) per query
  /tmp/oga/<name>.html      the OpenGameArt pages the music came from
"""
import html, json, os, re, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "game", "CREDITS.md")
picks = json.load(open("/tmp/audio_credits.json"))
meta = json.load(open("/tmp/fs/meta.json"))
fs = {}
for cat, rows in meta.items():
    for r in rows: fs[str(r["id"])] = r

free = defaultdict(set)          # (id, user, title) -> sets
kenney = defaultdict(set)
oga = []
for sset, path in picks:
    if path.startswith("/tmp/fs/"):
        fid = os.path.splitext(os.path.basename(path))[0]
        r = fs.get(fid, {"id": fid, "user": "?", "title": "?"})
        free[(fid, r["user"], r["title"])].add(sset)
    elif path.startswith("/tmp/kn/"):
        pack = path.split("/")[3].replace("kenney_", "").replace("-", " ").title()
        kenney[pack].add(sset)
    elif path.startswith("/tmp/oga/"):
        base = os.path.splitext(os.path.basename(path))[0]
        h = open("/tmp/oga/%s.html" % base, encoding="utf-8", errors="ignore").read()
        t = re.search(r"<title>(.*?)</title>", h, re.S)
        title = html.unescape(t.group(1)).split("|")[0].strip() if t else base
        a = re.findall(r'field-name-author-submitter.*?<a href="/users/([^"]+)"[^>]*>([^<]+)</a>', h, re.S)
        user = a[0][1] if a else "?"
        slug = a[0][0] if a else ""
        link = re.search(r'<link rel="canonical" href="([^"]+)"', h)
        oga.append((sset, title, user, link.group(1) if link else "https://opengameart.org"))

L = []
L.append("# Credits\n")
L.append("Ronin's Edge is built in Godot 4.3. The world, props, most textures and the enemy")
L.append("characters are generated by the project's own scripts (`v2/`, `v3/`, `v4/`, `tools/` in the")
L.append("dev-tools zip). Everything else comes from the free sources below. **Every third-party")
L.append("asset is CC0 1.0 (public domain) except the two fonts, which are SIL Open Font")
L.append("Licence 1.1** (texts in `assets/fonts/LICENSE.txt`). CC0 needs no attribution; it is")
L.append("given here with thanks.\n")
L.append("## Characters, animation, horse\n")
L.append("| What | Source | Author | Licence |")
L.append("|---|---|---|---|")
L.append("| Player body, head, eyes, hair (`assets/char/Ronin.glb`) | Universal Base Characters (Superhero Male) + hair pack | Quaternius — quaternius.com | CC0 1.0 |")
L.append("| Player clothing (\"Male Peasant\" outfit, recoloured) | Modular Outfits | Quaternius | CC0 1.0 |")
L.append("| Animation clips without a prefix (`assets/anim/ronin_anims.res`) | Universal Animation Library 1 & 2 | Quaternius | CC0 1.0 |")
L.append("| Animation clips with a `K_` prefix (dodges, kick, 2-handed moves, strafes, blocks) | KayKit Character Animations 1.1, retargeted by `tools/bake_kaykit.gd` | Kay Lousberg — kaylousberg.com | CC0 1.0 |")
L.append("| Horse (`assets/horse/`) — v0.13 `HorseHQ.glb` is the same horse smoothed, re-textured and given a mane/tail by `tools/horse_hq.py` | Animals pack | Quaternius | CC0 1.0 |")
L.append("| Weapons, saddle, props, buildings | modelled by the project's scripts | — | — |\n")
L.append("## Ground textures (v0.13)\n")
L.append("From **Poly Haven** (polyhaven.com, CC0 1.0), packed by `tools/make_ground_arrays.py`:")
L.append("Sparse Grass, Forest Leaves 02, Rocky Trail, Mossy Rock, Brown Mud 02, River Small Rocks,")
L.append("Aerial Grass Rock (macro variation). The water noise, foam and waterfall textures are")
L.append("generated (`tools/make_water_noise.py`).\n")
L.append("## Tree bark and rock (v0.14)\n")
L.append("From **Poly Haven** (polyhaven.com, CC0 1.0), in `assets/textures/bark/` and `assets/textures/rock/`:")
L.append("Sakura Bark, Pine Bark, Japanese Cedar Bark, Trident Maple Bark (tree trunks and limbs), and")
L.append("Mossy Rock again for rocks and loose stones. Leaf and petal textures are generated")
L.append("(`tools/make_foliage_atlas.py`).\n")
L.append("## Fonts (v0.13)\n")
L.append("| Font | Use | Licence |")
L.append("|---|---|---|")
L.append("| Noto Sans (Regular, SemiBold, ExtraBold instances; subset) — Google / Noto project | HUD and menus | SIL OFL 1.1 |")
L.append("| Shippori Mincho B1 ExtraBold (subset) — FONTDASU | titles, zone banners, kanji | SIL OFL 1.1 |\n")
L.append("## Music (v0.13)\n")
L.append("All from **OpenGameArt.org**, CC0 1.0.\n")
L.append("| In game | Track | Composer |")
L.append("|---|---|---|")
for sset, title, user, link in oga:
    L.append("| %s | [%s](%s) | %s |" % (sset.replace("music_", ""), title.replace("|", "/"), link, user))
L.append("")
L.append("## Sound effects (v0.13)\n")
L.append("**Kenney** (kenney.nl, CC0 1.0): %s.\n" % ", ".join(
    "%s (%s)" % (p, ", ".join(sorted(s))) for p, s in sorted(kenney.items())))
L.append("**Freesound** (freesound.org), CC0 1.0 uploads, trimmed / levelled / converted by the")
L.append("build script. Freesound id — uploader — title — used for:\n")
L.append("| id | uploader | title | used for |")
L.append("|---|---|---|---|")
for (fid, user, title), sets in sorted(free.items(), key=lambda x: (sorted(x[1])[0], x[0][0])):
    L.append("| [%s](https://freesound.org/s/%s/) | %s | %s | %s |" % (fid, fid, user, title.replace("|", "/"), ", ".join(sorted(sets))))
L.append("")
L.append("CC0 1.0: https://creativecommons.org/publicdomain/zero/1.0/  ")
L.append("SIL OFL 1.1: https://openfontlicense.org")
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", OUT, len(L), "lines;", len(free), "freesound,", len(oga), "music,", len(kenney), "kenney packs")
